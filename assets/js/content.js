/* ------------------------------------------------------------
   Применение: находит [data-content="hero.figureValue"] и
   подставляет значение по этому пути.
   ------------------------------------------------------------ */
(function applyContent() {
  const get = (path) =>
    path.split(".").reduce((acc, key) => (acc == null ? acc : acc[key]), window.CONTENT);

  document.querySelectorAll("[data-content]").forEach((el) => {
    const value = get(el.dataset.content);
    if (typeof value === "string") el.textContent = value;
  });

  // Флаги: [data-flag="caseBeeline"] скрывается, если флаг выключен
  document.querySelectorAll("[data-flag]").forEach((el) => {
    el.hidden = !window.CONTENT.flags[el.dataset.flag];
  });
})();
